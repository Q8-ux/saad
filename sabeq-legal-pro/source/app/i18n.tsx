const DICTIONARIES: Record<Exclude<Language, "ar">, Record<string, string>> = {
  en: EN,
  ur: UR,
};

const I18nContext = createContext<I18nValue | null>(null);

function interpolate(template: string, params?: Params) {
  if (!params) return template;
  return Object.entries(params).reduce(
    (value, [key, replacement]) =>
      value.replaceAll(`{{${key}}}`, String(replacement)),
    template,
  );
}

const LANGUAGE_STORAGE_KEY = "legal-office-language";
const LANGUAGE_EVENT = "legal-office-language-change";
let inMemoryLanguage: Language | null = null;

function readLanguagePreference(): Language {
  if (inMemoryLanguage) return inMemoryLanguage;
  try {
    const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (stored === "ar" || stored === "en" || stored === "ur") return stored;
  } catch { /* Language switching still works when storage is unavailable. */ }
  return "ar";
}

function subscribeToLanguage(onChange: () => void) {
  const onStorage = () => { inMemoryLanguage = null; onChange(); };
  window.addEventListener("storage", onStorage);
  window.addEventListener(LANGUAGE_EVENT, onChange);
  return () => {
    window.removeEventListener("storage", onStorage);
    window.removeEventListener(LANGUAGE_EVENT, onChange);
  };
}

function setLanguagePreference(language: Language) {
  inMemoryLanguage = language;
  try { window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language); } catch {}
  window.dispatchEvent(new Event(LANGUAGE_EVENT));
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const language = useSyncExternalStore(subscribeToLanguage, readLanguagePreference, (): Language => "ar");

  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = language === "en" ? "ltr" : "rtl";
    document.documentElement.dataset.language = language;
  }, [language]);

  const value = useMemo<I18nValue>(() => {
    const direction = language === "en" ? "ltr" : "rtl";
    const locale = language === "ar" ? "ar-KW" : language === "ur" ? "ur-PK" : "en-KW";
    return {
      language,
      setLanguage: setLanguagePreference,
      direction,
      locale,
      t: (key: string, params?: Params) => {
        const translated = language === "ar" ? key : DICTIONARIES[language][key] ?? key;
        return interpolate(translated, params);
      },
    };
  }, [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("I18nProvider is missing");
  return value;
}
