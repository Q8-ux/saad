const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'../..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const home=read('tamweenat/index.html');
const admin=read('tamweenat-admin/index.html');
const workflows=JSON.parse(read('tamweenat-admin/internal-workflows.json'));
assert(home.includes('كتالوج احتياجات مطاعم البرجر'));
assert(home.includes('renderFilters()'));
const catalog=JSON.parse(read('tamweenat/catalog.json'));
assert(catalog.length>0);
assert(new Set(catalog.map(p=>p.category)).size>=8);
assert(catalog.every(p=>p.active!==true || (Number(p.price)>0 && !String(p.priceStatus||'').startsWith('reference'))));
assert(home.includes("fetch('./catalog-photos.json'"));
const photos=JSON.parse(read('tamweenat/catalog-photos.json'));
assert(photos.length>=100);
assert(photos.every(p=>p.active!==true));
assert(photos.filter(p=>p.imageUrl).length>=100);
assert(photos.every(p=>p.nameEn && p.nameUr && p.categoryEn && p.categoryUr && p.unitEn && p.unitUr));
assert(photos.every(p=>!/[A-Za-z]/.test(p.nameUr)));
assert(home.includes('nameOf=p=>') && home.includes('categoryOf=p=>'));
assert(read('tamweenat/assistant-v1.js').includes('p.nameUr'));
assert(read('tamweenat/storefront-v6.css').includes('Cairo'));
assert(home.includes('assistant-v1.js'));
assert(home.includes('meal-planner-v1.js'));
const planner=read('tamweenat/meal-planner-v1.js');
assert(planner.includes('chicken') && planner.includes('beef'));
assert(planner.includes('TamweenatMealPlanner'));
assert(read('tamweenat/assistant-v1.js').includes('tw-voice-toggle'));
assert(read('tamweenat/assistant-v1.js').includes('TamweenatMealPlanner?.handle'));
assert(!/voice-assistant\.js|talking-path\.js|guest=1/.test(home));
assert(!/ops-tracks\.js|مركز المسارات الذكية/.test(admin));
assert(workflows.tracks.length===10);
assert(!/user\.value='restaurant1'|pass\.value='123456'/.test(read('tamweenat/login.html')));
assert(read('tamweenat-admin/admin-v23.css').includes('[hidden]{display:none!important}'));
assert(workflows.admin_ui_exposure===false&&workflows.customer_ui_exposure===false);
assert(workflows.rules.no_auto_write===true);
console.log('Tamweenat smoke checks passed');
